// Story voices, step 3: write the recordings into the files the game downloads.
//   node tools/story/pack.js
// voices/story.js       every line anyone except your hero says (loaded when story mode opens)
// voices/hero-<id>.js   the lines that hero says, plus lines that say the hero's name
const fs = require('fs');
const path = require('path');
const jobs = JSON.parse(fs.readFileSync(path.join(__dirname, 'jobs.json'), 'utf8'));
const clips = JSON.parse(fs.readFileSync(path.join(__dirname, 'story_clips.json'), 'utf8'));
const outDir = path.join(__dirname, '..', '..', 'voices');
fs.mkdirSync(outDir, { recursive: true });
const files = {};
let missing = 0;
for (const j of jobs) {
  if (!clips[j.key]) {
    missing++;
    continue;
  }
  (files[j.file] = files[j.file] || {})[j.key] = clips[j.key];
}
let total = 0;
for (const [name, map] of Object.entries(files)) {
  const body =
    '// Spoken story lines (generated by tools/story — do not edit by hand). { key: base64 MP3 }\n' +
    'window.SOCK_STORY_VOICES = Object.assign(window.SOCK_STORY_VOICES || {}, ' + JSON.stringify(map) + ');\n';
  fs.writeFileSync(path.join(outDir, name + '.js'), body);
  total += body.length;
  console.log(name.padEnd(14), String(Object.keys(map).length).padStart(4), 'lines', (body.length / 1e6).toFixed(2), 'MB');
}
console.log('total', (total / 1e6).toFixed(1), 'MB;', missing, 'lines not recorded yet');
// version stamps: a short hash of every voice file, written into the game so changed files are fetched fresh
const crypto = require('crypto');
const ver = {};
for (const name of Object.keys(files).sort())
  ver[name] = crypto.createHash('md5').update(fs.readFileSync(path.join(outDir, name + '.js'))).digest('hex').slice(0, 8);
const gamePath = path.join(__dirname, '..', '..', 'index.html');
const game = fs.readFileSync(gamePath, 'utf8');
const re = /const VOICE_FILE_VER = {[^}]*};/;
if (!re.test(game)) throw new Error('VOICE_FILE_VER not found in index.html');
fs.writeFileSync(gamePath, game.replace(re, () => 'const VOICE_FILE_VER = ' + JSON.stringify(ver) + ';'));
console.log('version stamps written for', Object.keys(ver).length, 'voice files');
