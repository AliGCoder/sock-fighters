// Writes baked voice clips into index.html's JSON data blocks (re-runnable).
//   node inject.js           announcer: clips.json         -> <script id="announcer-clips">
//   node inject.js fighter   fighters:  fighter_clips.json -> <script id="fighter-clips"> (created if missing)
const fs = require('fs'), path = require('path');
const file = path.join(__dirname, '..', '..', 'index.html');
const fighter = process.argv[2] === 'fighter';
const id = fighter ? 'fighter-clips' : 'announcer-clips';
const clips = JSON.parse(fs.readFileSync(path.join(__dirname, fighter ? 'fighter_clips.json' : 'clips.json'), 'utf8'));
let src = fs.readFileSync(file, 'utf8');
const before = src.length;
const re = new RegExp('(<script type="application/json" id="' + id + '">)[\\s\\S]*?(</script>)');
if (!re.test(src)) {
  if (!fighter) throw new Error('announcer-clips block not found');
  const block = '<!-- Fighter voice clips (base64 MP3 per character and word). Generated by tools/announcer/qwen_fighters.py + inject.js — do not edit by hand. -->\n' +
    '    <!-- prettier-ignore -->\n    <script type="application/json" id="fighter-clips"></script>\n    ';
  const at = src.indexOf('<!-- Announcer voice clips');
  if (at < 0) throw new Error('could not find where to add the fighter-clips block');
  src = src.slice(0, at) + block + src.slice(at);
}
src = src.replace(re, (_, open, close) => open + JSON.stringify(clips) + close);
fs.writeFileSync(file, src);
const count = fighter ? Object.values(clips).reduce((n, c) => n + Object.values(c).reduce((m, l) => m + l.length, 0), 0) : Object.keys(clips).length;
console.log(count + ' clips injected into #' + id + '; index.html ' + (before / 1e6).toFixed(2) + ' -> ' + (src.length / 1e6).toFixed(2) + ' MB');
